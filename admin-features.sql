-- Supabase SQL for the TOA Admin feature updates.
-- Run this once in Supabase SQL Editor.

-- Allow named customer reviews to store an uploaded customer photo.
DO $$
BEGIN
  IF to_regclass('public.reviews') IS NOT NULL THEN
    ALTER TABLE public.reviews
      ADD COLUMN IF NOT EXISTS photo_url text;

    COMMENT ON COLUMN public.reviews.photo_url IS
      'Storage path for the customer photo shown with the review.';
  END IF;
END $$;

-- Keep shop-home media separate from the existing Instagram gallery.
CREATE TABLE IF NOT EXISTS public.home_content (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  media_path text NOT NULL,
  media_type text NOT NULL DEFAULT 'image' CHECK (media_type IN ('image', 'video')),
  caption text,
  position integer NOT NULL DEFAULT 1,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.home_content
  ADD COLUMN IF NOT EXISTS media_type text NOT NULL DEFAULT 'image'
  CHECK (media_type IN ('image', 'video'));

COMMENT ON TABLE public.home_content IS
  'Media displayed in the shop home section; independent from the Instagram gallery.';

ALTER TABLE public.home_content ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON TABLE public.home_content TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.home_content TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.home_content_id_seq TO authenticated;

DROP POLICY IF EXISTS "Public can read active home content" ON public.home_content;
CREATE POLICY "Public can read active home content"
  ON public.home_content
  FOR SELECT
  TO anon, authenticated
  USING (active = true);

DROP POLICY IF EXISTS "Owners manage home content" ON public.home_content;
CREATE POLICY "Owners manage home content"
  ON public.home_content
  FOR ALL
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role = 'owner'
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role = 'owner'
    )
  );

-- Store product hashtag assignments in the existing settings table.
DO $$
BEGIN
  IF to_regclass('public.settings') IS NOT NULL THEN
    INSERT INTO public.settings (key, value)
    VALUES ('hashtags', '{}')
    ON CONFLICT (key) DO NOTHING;
  END IF;
END $$;

-- Remove the product-images bucket file-size limit.
-- A NULL file_size_limit means the bucket is not limited by Supabase.
-- NULL allowed_mime_types allows the existing admin page to upload photos,
-- GIFs, animations, and videos.
DO $$
BEGIN
  IF to_regclass('storage.buckets') IS NOT NULL THEN
    INSERT INTO storage.buckets (
      id,
      name,
      public,
      file_size_limit,
      allowed_mime_types
    )
    VALUES (
      'product-images',
      'product-images',
      true,
      NULL,
      NULL
    )
    ON CONFLICT (id) DO UPDATE
    SET
      public = true,
      file_size_limit = NULL,
      allowed_mime_types = NULL;
  END IF;
END $$;
